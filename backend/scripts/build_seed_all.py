"""Build every seed file in order, merge skus.json, validate. Fails loudly on bad data.

    uv run python -m scripts.build_seed_all              # OFF + FoodKeeper + merge + validate
    uv run --group seed python -m scripts.build_seed_all --favorita   # + Favorita (slow)
NOAA is snapshotted separately (scripts/snapshot_noaa.py) because it changes the sim baseline."""

import argparse
import math
from typing import Literal

from pydantic import BaseModel, Field, field_validator

from scripts import build_seed_favorita, build_seed_foodkeeper, build_seed_off
from scripts._common import SEED, SKU_BASE, read_json, write_json


class OffMeta(BaseModel):
    barcode: str | None
    product_name: str | None
    nutri_score: Literal["a", "b", "c", "d", "e"] | None
    packaging: str | None
    ethylene: Literal["producer", "sensitive", "neutral"]


class SkuSeed(BaseModel):
    sku_id: str
    name: str
    category: str
    unit_weight_kg: float = Field(gt=0)
    base_price_usd: float = Field(gt=0)
    unit_cost_usd: float = Field(gt=0)
    sl_nominal_hours: float = Field(gt=0)
    sl_source: str
    elasticity: float = Field(lt=0)
    price_floor_ratio: float = Field(gt=0, le=1)
    base_daily_units: float = Field(gt=0)
    weather_exposure: float = Field(ge=0, le=1)
    bundle_group: str | None
    supplier: str
    delivery_every_days: int = Field(ge=1, le=7)
    off: OffMeta
    sources: list[str]


class CategoryFao(BaseModel):
    fao_group: str
    retail_waste_pct: float = Field(ge=0, le=100)
    co2e_kg_per_kg: float = Field(gt=0)
    co2e_item: str


class Profile(BaseModel):
    hour_share: dict[str, list[float]]
    dow_weight: dict[str, list[float]]

    @field_validator("hour_share")
    @classmethod
    def _hours(cls, v):
        for k, w in v.items():
            assert len(w) == 24 and sum(w) > 0, f"hour_share[{k}] needs 24 weights"
            assert all(w[h] == 0 for h in (*range(7), 22, 23)), f"hour_share[{k}] open 7-21 only"
        return v

    @field_validator("dow_weight")
    @classmethod
    def _dow(cls, v):
        for k, w in v.items():
            assert len(w) == 7 and math.isclose(sum(w) / 7, 1, abs_tol=0.01), f"dow_weight[{k}]"
        return v


class Weather(BaseModel):
    source: str
    relative_humidity_pct: float = Field(ge=0, le=100)
    p_heavy_rain_by_day: list[float] = Field(min_length=7)


def merge(off: dict, fk: dict | None) -> list[dict]:
    eth = read_json(SEED / "ethylene.json")
    prev = SEED / "foodkeeper.json"
    if fk is None and prev.exists():  # keep previously built FoodKeeper values
        fk = {r["sku_id"]: r for r in read_json(prev)}
    fk = fk or {}
    out = []
    for s in read_json(SKU_BASE)["skus"]:
        sid = s["sku_id"]
        f = fk.get(sid)
        sources = []
        if f and f["sl_nominal_hours"]:
            sl, sl_src = (
                f["sl_nominal_hours"],
                f"USDA FoodKeeper #{f['foodkeeper_id']}: {f['name']} ({f['storage']})",
            )
            sources.append(sl_src)
        else:
            sl, sl_src = s["sl_nominal_hours"], "illustrative (FoodKeeper not yet merged)"
        o = off[sid]
        if o["barcode"]:
            sources.append(f"Open Food Facts {o['barcode']}")
        sources.append(f"Ethylene: {eth['skus'][sid]['class']}")
        sources.append("Elasticity: assumed")
        out.append(
            {
                **{k: s[k] for k in SkuSeed.model_fields if k in s and k not in ("off", "sources")},
                "sl_nominal_hours": sl,
                "sl_source": sl_src,
                "off": {
                    **o,
                    "packaging": o["packaging"] or s["packaging"],
                    "ethylene": eth["skus"][sid]["class"],
                },
                "sources": sources,
            }
        )
    return out


def validate(skus: list[dict]) -> None:
    print("Validating")
    for s in skus:
        SkuSeed.model_validate(s)
    fao = read_json(SEED / "faostat.json")["categories"]
    for c in {s["category"] for s in skus}:
        CategoryFao.model_validate(fao[c])
    prof = Profile.model_validate(read_json(SEED / "sales_profile.json"))
    for c in {s["category"] for s in skus}:
        assert c in prof.dow_weight or "default" in prof.dow_weight, c
    Weather.model_validate(read_json(SEED / "weather_snapshot.json"))
    print(f"  ok — {len(skus)} SKUs")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--favorita", action="store_true", help="also rebuild Favorita aggregates")
    a = ap.parse_args()
    off = build_seed_off.build()
    fk = build_seed_foodkeeper.build()
    if a.favorita:
        build_seed_favorita.build()
    skus = merge(off, fk)
    validate(skus)
    write_json(
        SEED / "skus.json",
        {
            "_note": "GENERATED by scripts/build_seed_all.py from sku_base.json. Do not edit.",
            "skus": skus,
        },
    )


if __name__ == "__main__":
    main()
